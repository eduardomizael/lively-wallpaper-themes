const assert = require('node:assert/strict'), vm = require('node:vm'), fs = require('node:fs'), path = require('node:path');
const context = vm.createContext({ window: {}, Math });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../atmosphere.js'), 'utf8'), context);
const A = context.window.CircuitAtmosphere;
const field = new A.Atmosphere(3440, 1440);
assert.equal(field.dust.length, 70);
assert.equal(field.moving({ fogStrength: 0, dustCount: 0 }), false);
assert.equal(field.moving({ fogStrength: 45, dustCount: 0 }), true);
for (let i = 0; i < 100; i++) field.impact({ x: 100, y: 100, radius: 29 });
assert.equal(field.waves.length, 6, 'Impact history is bounded');
field.update(1.61); assert.equal(field.waves.length, 0, 'Impact waves expire');
field.resize(1920,1080); assert.equal(field.dust.length, 70);
let cachedCanvases = 0, images = 0, points = 0, patterns = 0;
const gradient = { addColorStop() {} };
const ctx = { createRadialGradient: () => gradient, fillRect() { points++; }, drawImage() { images++; }, createPattern() { patterns++; return {}; } };
const sprites = A.createSprites((width,height) => {
  cachedCanvases++;
  const canvas = {width,height};
  canvas.getContext = () => ({...ctx,createImageData:(w,h)=>({width:w,height:h,data:new Uint8ClampedArray(w*h*4)}),putImageData:image=>{canvas.pixels=image;}});
  return canvas;
}, '#49e5ff');
assert.equal(cachedCanvases, 5);
assert.equal(sprites.cloud.width, 512);
const alphaAt = (sprite,x,y)=>sprite.pixels.data[(y*512+x)*4+3];
assert.ok(alphaAt(sprites.mouse,256,256)<alphaAt(sprites.cloud,256,256), 'Mouse cloud has a lower central peak');
assert.ok(alphaAt(sprites.mouse,384,256)/alphaAt(sprites.mouse,256,256)>alphaAt(sprites.cloud,384,256)/alphaAt(sprites.cloud,256,256)+.1, 'Mouse profile spreads brightness more evenly');
assert.ok(sprites.grain.pixels.data.every((value,index)=>index%4!==3||value<=2), 'Final dithering stays below one percent opacity');
points = 0;
for (let i = 0; i < 1000; i++) { field.update(.016); A.drawFog(ctx,field,sprites,45); }
assert.equal(cachedCanvases, 5, 'Fog frames reuse cached textures');
assert.equal(patterns, 1, 'The dithering pattern is cached');
assert.equal(images, 3000);
points=0;
A.drawDetails(ctx,field,sprites,{dustCount:32,impactStrength:0},a=>`rgba(73,229,255,${a})`);
assert.equal(points, 32, 'Dust count is configurable');
images = 0; points = 0;
A.drawFog(ctx,field,sprites,0);
A.drawDetails(ctx,field,sprites,{dustCount:0,impactStrength:0},a=>String(a));
assert.equal(images, 0); assert.equal(points, 0);
assert.equal(ctx.globalAlpha, 1);
const mouseOnly = {fogStrength:0,dustCount:0,mouseFog:true,mouseFogStrength:35,mouseFogSize:160};
assert.equal(field.movePointer(100,100), false, 'First event only establishes the cursor position');
assert.equal(field.moving(mouseOnly), false);
assert.equal(field.movePointer(180,150), true);
assert.equal(field.moving(mouseOnly), true, 'Mouse movement wakes a static scene');
field.update(.016);
assert.ok(field.cursor.x > 100 && field.cursor.x < 180, 'Cloud follows with a small lag');
assert.ok(field.cursor.strength > 0);
for (let i=0;i<150;i++) { field.movePointer(180,150); field.update(.016); }
assert.equal(field.cursor.strength, 0, 'Repeated stationary input cannot sustain a halo');
assert.equal(field.cursorPuffs.length, 0);
assert.equal(field.moving(mouseOnly), false, 'Scene can sleep again after the cloud dissipates');
for (let i=0;i<1000;i++) { field.movePointer(200+Math.sin(i*.1)*50,200); field.update(.016); assert.ok(field.cursorPuffs.length <= 16); }
field.movePointer(1900,1000);
assert.equal(field.cursorPuffs.length, 0, 'A jump to another monitor does not draw a connecting trail');
assert.equal(field.cursor.strength, 0);
assert.equal(field.movePointer(-1,200), false, 'Off-screen coordinates do not emit clouds');
field.resize(1280,720); assert.equal(field.cursor,null); assert.equal(field.cursorPuffs.length,0);
console.log('Nevoa em cache, particulas limitadas, ondas finitas e controles: OK');
